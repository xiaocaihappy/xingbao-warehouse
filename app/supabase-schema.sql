-- ============================================
-- 11. 仓储人员列表（所有用户实时同步）
-- ============================================
CREATE TABLE IF NOT EXISTS public.staff_list (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  is_default BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_staff_list_name ON public.staff_list(name);

ALTER TABLE public.staff_list ENABLE ROW LEVEL SECURITY;

CREATE POLICY "允许认证用户读取人员" ON public.staff_list
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "允许认证用户添加人员" ON public.staff_list
  FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "允许认证用户删除人员" ON public.staff_list
  FOR DELETE TO authenticated USING (is_default = false);

-- 启用 Realtime
ALTER PUBLICATION supabase_realtime ADD TABLE public.staff_list;

