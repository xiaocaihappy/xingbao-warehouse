-- 请在 Supabase SQL Editor 中执行以下 SQL
-- ============================================

-- 1. 创建 samples 表
CREATE TABLE IF NOT EXISTS public.samples (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  name TEXT NOT NULL,
  category TEXT DEFAULT '移印样品',
  location TEXT NOT NULL,
  quantity INTEGER DEFAULT 1,
  status TEXT DEFAULT 'in_stock' CHECK (status IN ('in_stock', 'out_stock', 'reserved')),
  image_url TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 创建索引加速查询
CREATE INDEX IF NOT EXISTS idx_samples_code ON public.samples(code);
CREATE INDEX IF NOT EXISTS idx_samples_name ON public.samples(name);
CREATE INDEX IF NOT EXISTS idx_samples_category ON public.samples(category);
CREATE INDEX IF NOT EXISTS idx_samples_status ON public.samples(status);
CREATE INDEX IF NOT EXISTS idx_samples_location ON public.samples(location);
CREATE INDEX IF NOT EXISTS idx_samples_created_at ON public.samples(created_at DESC);

-- 3. 启用 Row Level Security (RLS)
ALTER TABLE public.samples ENABLE ROW LEVEL SECURITY;

-- 4. 创建 RLS 策略 - 允许认证用户读取所有数据
CREATE POLICY "允许认证用户读取" ON public.samples
  FOR SELECT
  TO authenticated
  USING (true);

-- 5. 允许认证用户插入数据
CREATE POLICY "允许认证用户插入" ON public.samples
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- 6. 允许认证用户更新数据
CREATE POLICY "允许认证用户更新" ON public.samples
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- 7. 允许认证用户删除数据
CREATE POLICY "允许认证用户删除" ON public.samples
  FOR DELETE
  TO authenticated
  USING (true);

-- 8. 启用 Realtime 订阅（用于多人实时编辑）
ALTER PUBLICATION supabase_realtime ADD TABLE public.samples;

